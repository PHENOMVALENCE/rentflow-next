// Collects literal phrases passed to t(...) / plural(t, n, ...) in client components into
// src/i18n/client-phrases.generated.ts, so only those translations are shipped to the browser.
// Run: node scripts/extract-client-phrases.mjs   (a unit test fails when the output is stale)
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("../src", import.meta.url).pathname;
const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (/\.tsx?$/.test(name) && !name.endsWith(".test.ts")) files.push(path);
  }
};
walk(root);

export function extract(source) {
  const phrases = new Set();
  const str = String.raw`"((?:[^"\\]|\\.)*)"`;
  for (const match of source.matchAll(new RegExp(String.raw`\bt\(\s*${str}`, "g"))) phrases.add(JSON.parse(`"${match[1]}"`));
  for (const match of source.matchAll(new RegExp(String.raw`\bplural\(\s*t\s*,[^,]+,\s*${str}\s*,\s*${str}`, "g"))) {
    phrases.add(JSON.parse(`"${match[1]}"`));
    phrases.add(JSON.parse(`"${match[2]}"`));
  }
  return phrases;
}

export function collect() {
  const all = new Set();
  for (const file of files) {
    const source = readFileSync(file, "utf8");
    if (!/^["']use client["']/.test(source.trimStart())) continue;
    for (const phrase of extract(source)) all.add(phrase);
  }
  return [...all].sort();
}

export function render(phrases) {
  return `// Generated by scripts/extract-client-phrases.mjs — do not edit by hand.\nexport const EXTRACTED_CLIENT_PHRASES: readonly string[] = ${JSON.stringify(phrases, null, 2)};\n`;
}

if (process.argv[1] && process.argv[1].endsWith("extract-client-phrases.mjs")) {
  const out = join(root, "i18n/client-phrases.generated.ts");
  writeFileSync(out, render(collect()));
  console.log(`wrote ${out}`);
}
